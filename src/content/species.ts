export const ELEMENTS = [
  "H",
  "C",
  "N",
  "O",
  "F",
  "Na",
  "Al",
  "P",
  "S",
  "Cl",
  "K",
  "Ca",
  "Ti",
  "Mn",
  "Fe",
  "Zn",
  "Ag",
] as const;

export type ElementSymbol = (typeof ELEMENTS)[number];

export interface Species {
  id: string;
  label: string;
  plain: string;
  atoms: Partial<Record<ElementSymbol, number>>;
  /** Charge of one formula unit. An electron is −1. A photon is 0. */
  charge: number;
}

function spec(
  label: string,
  plain: string,
  atoms: Partial<Record<ElementSymbol, number>>,
  charge: number,
): Omit<Species, "id"> {
  return { label, plain, atoms, charge };
}

